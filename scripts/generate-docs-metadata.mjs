#!/usr/bin/env node
// AAASM-4312 / AAASM-4327 / Epic AAASM-4309
//
// Node SDK docs metadata generator. Reads authoritative values from
// `package.json` (name, version, homepage, repository) plus shared docs-only
// values from `metadata/sdk.json` (docs URL, npm dist-tag, install-command
// templates, CLI package name) and rewrites BOUNDED generated blocks in-place
// inside README.md and docs/**. Surrounding prose is preserved byte-for-byte.
//
// Generated blocks use sentinel comments. GitHub-rendered Markdown surfaces
// (README.md, CONTRIBUTING.md) use HTML comments; MDX-processed docs under
// `docs/**` use MDX expression comments — Docusaurus v3's MDX parser rejects
// bare `<!--` and would fail the site build otherwise.
//
//   README / CONTRIBUTING  →  <!-- BEGIN GENERATED: <id> --> ... <!-- END GENERATED: <id> -->
//   docs/** (MDX)          →  {/* BEGIN GENERATED: <id> */} ... {/* END GENERATED: <id> */}
//
// A block that is not present in a target file is skipped silently — only the
// blocks that already exist are rewritten. This lets docs authors opt a page
// in by pasting an empty pair of sentinels once, using the syntax that matches
// the file's rendering environment.
//
// In addition to the bounded-block rewrite pass, the generator emits an
// entire TypeScript module — `src/generated/install-hints.ts` — that runtime
// source code imports for the same install-command strings (AAASM-4327). The
// file is fully overwritten on every run so `git diff --exit-code` catches
// drift the same way it does for docs.
//
// Zero network access. Reads local repo state only.
//
// Run from the repo root:  pnpm run generate:docs-metadata
// CI check:                pnpm run generate:docs-metadata && git diff --exit-code

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve, relative } from "node:path";

// Comment-syntax dialect per file. HTML is safe on GitHub-rendered Markdown;
// MDX is required for anything Docusaurus loads through its MDX pipeline.
const DIALECTS = {
  html: {
    kind: "html",
    header: (id) =>
      `<!-- GENERATED BY scripts/generate-docs-metadata.mjs \u2014 DO NOT EDIT. Block: ${id}. -->`,
    beginRe: (id) =>
      new RegExp(
        `<!--\\s*BEGIN GENERATED:\\s*${id}\\s*-->[\\s\\S]*?<!--\\s*END GENERATED:\\s*${id}\\s*-->`,
        "g"
      ),
    begin: (id) => `<!-- BEGIN GENERATED: ${id} -->`,
    end: (id) => `<!-- END GENERATED: ${id} -->`
  },
  mdx: {
    kind: "mdx",
    header: (id) =>
      `{/* GENERATED BY scripts/generate-docs-metadata.mjs \u2014 DO NOT EDIT. Block: ${id}. */}`,
    beginRe: (id) =>
      new RegExp(
        `\\{\\/\\*\\s*BEGIN GENERATED:\\s*${id}\\s*\\*\\/\\}[\\s\\S]*?\\{\\/\\*\\s*END GENERATED:\\s*${id}\\s*\\*\\/\\}`,
        "g"
      ),
    begin: (id) => `{/* BEGIN GENERATED: ${id} */}`,
    end: (id) => `{/* END GENERATED: ${id} */}`
  }
};

// Files under docs/** are MDX-parsed by Docusaurus. Everything else defaults
// to HTML-comment sentinels (GitHub-rendered Markdown).
function dialectFor(relPath) {
  return relPath.startsWith("docs/") ? DIALECTS.mdx : DIALECTS.html;
}

// ---------------------------------------------------------------------------
// Metadata loading
// ---------------------------------------------------------------------------

export function loadMetadata(repoRoot) {
  const pkg = JSON.parse(
    readFileSync(resolve(repoRoot, "package.json"), "utf8")
  );
  const shared = JSON.parse(
    readFileSync(resolve(repoRoot, "metadata/sdk.json"), "utf8")
  );

  if (typeof pkg.name !== "string" || pkg.name.length === 0) {
    throw new Error("package.json is missing a `name` field");
  }
  if (typeof pkg.version !== "string" || pkg.version.length === 0) {
    throw new Error("package.json is missing a `version` field");
  }
  if (typeof shared.docsUrl !== "string" || shared.docsUrl.length === 0) {
    throw new Error("metadata/sdk.json is missing a `docsUrl` field");
  }
  if (typeof shared.distTag !== "string" || shared.distTag.length === 0) {
    throw new Error("metadata/sdk.json is missing a `distTag` field");
  }

  return {
    packageName: pkg.name,
    version: pkg.version,
    homepage: pkg.homepage ?? "",
    repositoryUrl:
      typeof pkg.repository === "object" && pkg.repository?.url
        ? String(pkg.repository.url)
        : "",
    docsUrl: shared.docsUrl,
    distTag: shared.distTag,
    cliInstall: shared.cliInstall ?? {},
    installCommands: shared.installCommands ?? {},
    quickstartTabs: loadQuickstartTabs(repoRoot)
  };
}

// ---------------------------------------------------------------------------
// Quick-start framework tabs (AAASM-4514 / Epic AAASM-4511)
//
// The per-framework tab list is data-driven: it is the node slice of a
// manifest VENDORED from the examples repo (AAASM-4512), plus each framework's
// verbatim `region: quickstart` snippet copied alongside it. Both live under
// `metadata/quickstart-snippets/` and are committed (never fetched at build
// time), so the tabs build offline and a stale committed doc is caught by the
// same regenerate-and-`git diff` drift gate as the other generated blocks.
//
// A framework's `status` (validated | experimental) is curated display
// metadata that drives ordering (validated first) and the tab label
// (experimental frameworks get an `(Experimental)` suffix). A missing manifest
// yields an empty tab list rather than a hard error, so the generator degrades
// gracefully if the vendored slice is absent.
// ---------------------------------------------------------------------------

export const QUICKSTART_SNIPPETS_DIR = "metadata/quickstart-snippets";

export function loadQuickstartTabs(repoRoot) {
  const manifestPath = resolve(
    repoRoot,
    QUICKSTART_SNIPPETS_DIR,
    "manifest.json"
  );
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  } catch {
    return [];
  }
  const entries = Array.isArray(manifest.node) ? manifest.node : [];
  const snippetsRoot = dirname(manifestPath);
  return entries.map((entry) => ({
    frameworkId: String(entry.framework_id),
    label: String(entry.label),
    status: entry.status === "experimental" ? "experimental" : "validated",
    lang: String(entry.lang ?? "typescript"),
    code: readFileSync(
      resolve(snippetsRoot, String(entry.snippet_path)),
      "utf8"
    ).replace(/\s+$/, ""),
    // Optional, curated (AAASM-4589): only set for a framework with a real,
    // citable import-path break across its own version history — verified
    // against that framework's own migration guide/changelog, never guessed.
    compatNote: entry.compat_note
      ? {
          title: String(entry.compat_note.title ?? "Version compatibility"),
          body: String(entry.compat_note.body)
        }
      : null
  }));
}

// ---------------------------------------------------------------------------
// Block renderers — each returns the INNER body of a named generated block
// (excluding the sentinels themselves). Keep each block small and focused so
// docs authors can adopt them independently.
// ---------------------------------------------------------------------------

// Package managers for the install-commands tabs, in display order (pnpm is
// this repo's primary tool — see CONTRIBUTING.md — so it is the default tab).
const INSTALL_PACKAGE_MANAGERS = [
  { id: "pnpm", label: "pnpm" },
  { id: "npm", label: "npm" },
  { id: "yarn", label: "yarn" },
  { id: "bun", label: "bun" }
];

function renderInstallCommands(meta, dialect) {
  const latest = meta.installCommands.latest ?? {};
  const fallback = {
    pnpm: `pnpm add ${meta.packageName}`,
    npm: `npm install ${meta.packageName}`,
    yarn: `yarn add ${meta.packageName}`,
    bun: `bun add ${meta.packageName}`
  };

  // README.md is rendered by GitHub, which has no Docusaurus `<Tabs>` support,
  // so it keeps the plain fenced block — one command per package manager,
  // joined by `# or`, in the same order as INSTALL_PACKAGE_MANAGERS so it
  // never drifts from the Tabs list below. Only MDX docs pages (Docusaurus)
  // get the Tabs/TabItem markup, same restriction as
  // renderQuickstartFrameworkTabs.
  if (dialect.kind !== "mdx") {
    const commandLines = INSTALL_PACKAGE_MANAGERS.flatMap(({ id }, i) => [
      ...(i > 0 ? ["# or"] : []),
      latest[id] ?? fallback[id]
    ]);
    return [
      dialect.header("install-commands"),
      "",
      "```bash",
      ...commandLines,
      "```"
    ].join("\n");
  }

  const lines = [dialect.header("install-commands"), ""];
  lines.push('<Tabs groupId="quickstart-install-package-manager">');
  INSTALL_PACKAGE_MANAGERS.forEach(({ id, label }, i) => {
    lines.push(
      `<TabItem value="${id}" label="${label}"${i === 0 ? " default" : ""}>`,
      "",
      "```bash",
      latest[id] ?? fallback[id],
      "```",
      "",
      "</TabItem>"
    );
  });
  lines.push("</Tabs>");
  return lines.join("\n");
}

function renderInstallDistTag(meta, dialect) {
  const dt = meta.installCommands.distTag ?? {};
  const pinnedTemplate =
    meta.installCommands.pinned?.pnpm ?? `pnpm add ${meta.packageName}@<VERSION>`;
  const pinnedExample = pinnedTemplate.replace("<VERSION>", meta.version);
  return [
    dialect.header("install-dist-tag"),
    "",
    "```bash",
    `${dt.pnpm ?? `pnpm add ${meta.packageName}@${meta.distTag}`}                # latest ${meta.distTag} (tracks @${meta.distTag} dist-tag)`,
    `${pinnedExample}      # pin exact \u2014 replace the version with the`,
    `                                               # desired release from npmjs.com/package/${encodeURIComponent(
      meta.packageName
    )}`,
    "```"
  ].join("\n");
}

function renderPackageIdentity(meta, dialect) {
  return [
    dialect.header("package-identity"),
    "",
    `- **Package name:** \`${meta.packageName}\``,
    `- **Current version:** \`${meta.version}\` (npm dist-tag \`${meta.distTag}\`)`,
    `- **Documentation:** ${meta.docsUrl}`,
    ...(meta.cliInstall?.brew
      ? [`- **CLI install:** \`${meta.cliInstall.brew}\``]
      : [])
  ].join("\n");
}

function renderCurrentVersionPin(meta, dialect) {
  const npmPinned =
    meta.installCommands.pinned?.npm ??
    `npm install ${meta.packageName}@<VERSION>`;
  return [
    dialect.header("current-version-pin"),
    "",
    `\`${npmPinned.replace("<VERSION>", meta.version)}\``
  ].join("\n");
}

// Fenced-code language tag per snippet `lang`. Keeps the doc fence in step with
// the snippet's real language without hard-coding it at the call site.
const FENCE_LANG = { typescript: "ts", javascript: "js" };

// Renders the quick-start per-framework tab block: one `<TabItem>` per Node
// framework, each holding its verbatim example snippet. Validated frameworks
// come first (stable-sorted by status) and render with a plain label; the
// first tab is the default. Experimental frameworks follow with an
// `(Experimental)` label suffix. Emits JSX, so it is only valid inside an MDX
// page — the sole target is docs/02-quick-start/index.md, whose top-of-file
// imports pull in `@theme/Tabs` / `@theme/TabItem`.
export function renderQuickstartFrameworkTabs(meta, dialect) {
  const tabs = [...(meta.quickstartTabs ?? [])].sort(
    (a, b) =>
      (a.status === "experimental" ? 1 : 0) -
      (b.status === "experimental" ? 1 : 0)
  );

  const lines = [dialect.header("quickstart-framework-tabs"), ""];
  lines.push('<Tabs groupId="quickstart-node-framework">');
  tabs.forEach((tab, i) => {
    const label =
      tab.status === "experimental" ? `${tab.label} (Experimental)` : tab.label;
    const fence = FENCE_LANG[tab.lang] ?? tab.lang;
    // Blank lines around the fence are required for Docusaurus MDX to parse a
    // code block nested inside a JSX <TabItem> element.
    lines.push(
      `<TabItem value="${tab.frameworkId}" label="${label}"${i === 0 ? " default" : ""}>`,
      "",
      "```" + fence,
      tab.code,
      "```",
      // A blank line before the fence's closing ``` is already required above;
      // the note needs the same blank-line isolation to parse as MDX inside a
      // JSX <TabItem>, same as the fence itself (see comment above this fn).
      ...(tab.compatNote
        ? ["", `:::note[${tab.compatNote.title}]`, tab.compatNote.body, ":::"]
        : []),
      "",
      "</TabItem>"
    );
  });
  lines.push("</Tabs>");
  return lines.join("\n");
}

// Map of block id -> renderer. Adding a new generated block means adding one
// entry here, wrapping the target snippet with matching sentinels, and re-running
// the generator. No other wiring is required.
const BLOCKS = {
  "install-commands": renderInstallCommands,
  "install-dist-tag": renderInstallDistTag,
  "package-identity": renderPackageIdentity,
  "current-version-pin": renderCurrentVersionPin,
  "quickstart-framework-tabs": renderQuickstartFrameworkTabs
};

// ---------------------------------------------------------------------------
// File rewrite
// ---------------------------------------------------------------------------

export function rewriteFile(filePath, meta, relPath) {
  const original = readFileSync(filePath, "utf8");
  const dialect = dialectFor(relPath);
  let updated = original;
  const rewritten = [];

  for (const [id, render] of Object.entries(BLOCKS)) {
    const re = dialect.beginRe(id);
    if (!re.test(updated)) continue;
    // Reset lastIndex — /g regex object was consumed by `.test()`.
    re.lastIndex = 0;
    const body = render(meta, dialect);
    const replacement = `${dialect.begin(id)}\n${body}\n${dialect.end(id)}`;
    updated = updated.replace(re, replacement);
    rewritten.push(id);
  }

  if (updated !== original) {
    writeFileSync(filePath, updated);
  }

  return { changed: updated !== original, rewritten };
}

// ---------------------------------------------------------------------------
// Source-code emitter — AAASM-4327
//
// Emits `src/generated/install-hints.ts`, a TypeScript module that runtime
// code imports for install-command strings so a package rename never leaves
// stale hints in user-facing error messages. The file is overwritten in full
// on every run and contains constant strings only — no logic, no top-level
// await, no experimental syntax — so it compiles cleanly under both the ESM
// and CJS build targets.
// ---------------------------------------------------------------------------

// Path (relative to repo root) of the emitted TS module. Kept in one place so
// the drift-check workflow scope stays trivially auditable.
export const INSTALL_HINTS_TS_PATH = "src/generated/install-hints.ts";

// Escape a value for embedding inside a TypeScript double-quoted string
// literal. Only the two characters that would otherwise close or escape the
// literal need handling — the shared metadata values are otherwise plain
// ASCII install commands.
function tsDoubleQuoted(value) {
  return `"${String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

export function renderInstallHintsModule(meta) {
  const sdkPackageName = meta.packageName;
  const pnpmSdk =
    meta.installCommands.latest?.pnpm ?? `pnpm add ${sdkPackageName}`;
  // The `aasm` CLI is not published as an npm package (AAASM-4796) \u2014 it ships
  // as a Homebrew formula / curl-installed binary, mirroring the manual
  // fallback already documented in src/runtime.ts's INSTALL_HINT.
  const brewCli = meta.cliInstall.brew ?? "brew install ai-agent-assembly/tap/aasm";
  const curlCli =
    meta.cliInstall.curl ?? "curl -fsSL https://agent-assembly.com/install.sh | sh";

  return [
    "// GENERATED BY scripts/generate-docs-metadata.mjs \u2014 DO NOT EDIT.",
    "// AAASM-4327 / Epic AAASM-4309.",
    "//",
    "// Source-of-truth: package.json (name) + metadata/sdk.json",
    "// (cliInstall, installCommands). Regenerate with:",
    "//   pnpm run generate:docs-metadata",
    "",
    `export const SDK_PACKAGE_NAME = ${tsDoubleQuoted(sdkPackageName)};`,
    `export const INSTALL_HINT_PNPM_SDK = ${tsDoubleQuoted(pnpmSdk)};`,
    `export const INSTALL_HINT_BREW_CLI = ${tsDoubleQuoted(brewCli)};`,
    `export const INSTALL_HINT_CURL_CLI = ${tsDoubleQuoted(curlCli)};`,
    ""
  ].join("\n");
}

export function writeInstallHintsModule(repoRoot, meta) {
  const abs = resolve(repoRoot, INSTALL_HINTS_TS_PATH);
  const body = renderInstallHintsModule(meta);
  let previous;
  try {
    previous = readFileSync(abs, "utf8");
  } catch {
    previous = null;
  }
  const changed = previous !== body;
  if (changed) {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, body);
  }
  return { changed };
}

// ---------------------------------------------------------------------------
// Entrypoint
// ---------------------------------------------------------------------------

// Files the generator considers. A file that has no matching sentinels is a
// no-op — this list is intentionally permissive so new generated blocks can be
// added without touching this script.
const TARGET_FILES = [
  "README.md",
  "docs/02-quick-start/index.md"
];

export function runGenerator({
  repoRoot,
  targets = TARGET_FILES,
  logger = console
} = {}) {
  const meta = loadMetadata(repoRoot);
  const results = [];
  for (const rel of targets) {
    const abs = resolve(repoRoot, rel);
    const result = rewriteFile(abs, meta, rel);
    results.push({ file: rel, ...result });
    if (result.changed) {
      logger.log(
        `[generate-docs-metadata] rewrote ${rel} (blocks: ${result.rewritten.join(", ")})`
      );
    }
  }

  const installHints = writeInstallHintsModule(repoRoot, meta);
  if (installHints.changed) {
    logger.log(
      `[generate-docs-metadata] rewrote ${INSTALL_HINTS_TS_PATH}`
    );
  }

  return { meta, results, installHints };
}

function main() {
  const scriptDir = dirname(fileURLToPath(import.meta.url));
  const repoRoot = resolve(scriptDir, "..");
  const { results, installHints } = runGenerator({ repoRoot });
  const changed = results.filter((r) => r.changed);
  const changedPaths = changed.map((c) =>
    relative(repoRoot, resolve(repoRoot, c.file))
  );
  if (installHints.changed) {
    changedPaths.push(INSTALL_HINTS_TS_PATH);
  }
  if (changedPaths.length === 0) {
    console.log(
      "[generate-docs-metadata] no generated blocks required rewriting"
    );
  } else {
    console.log(
      `[generate-docs-metadata] rewrote ${changedPaths.length} file(s): ${changedPaths.join(", ")}`
    );
  }
}

// Only run when executed directly (matches write-cjs-package-json.mjs pattern),
// so unit tests can import the pure functions without side effects.
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  main();
}
