#!/usr/bin/env node
// AAASM-4312 / Epic AAASM-4309
//
// Node SDK docs metadata generator. Reads authoritative values from
// `package.json` (name, version, homepage, repository) plus shared docs-only
// values from `metadata/sdk.json` (docs URL, npm dist-tag, install-command
// templates, CLI package name) and rewrites BOUNDED generated blocks in-place
// inside README.md and docs/**. Surrounding prose is preserved byte-for-byte.
//
// Generated blocks use sentinel comments. GitHub-rendered Markdown surfaces
// (README.md, CONTRIBUTING.md) use HTML comments; MDX-processed docs under
// `docs/**` use MDX expression comments — Docusaurus v3's MDX parser rejects
// bare `<!--` and would fail the site build otherwise.
//
//   README / CONTRIBUTING  →  <!-- BEGIN GENERATED: <id> --> ... <!-- END GENERATED: <id> -->
//   docs/** (MDX)          →  {/* BEGIN GENERATED: <id> */} ... {/* END GENERATED: <id> */}
//
// A block that is not present in a target file is skipped silently — only the
// blocks that already exist are rewritten. This lets docs authors opt a page
// in by pasting an empty pair of sentinels once, using the syntax that matches
// the file's rendering environment.
//
// Zero network access. Reads local repo state only.
//
// Run from the repo root:  pnpm run generate:docs-metadata
// CI check:                pnpm run generate:docs-metadata && git diff --exit-code

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve, relative } from "node:path";

// Comment-syntax dialect per file. HTML is safe on GitHub-rendered Markdown;
// MDX is required for anything Docusaurus loads through its MDX pipeline.
const DIALECTS = {
  html: {
    header: (id) =>
      `<!-- GENERATED BY scripts/generate-docs-metadata.mjs — DO NOT EDIT. Block: ${id}. -->`,
    beginRe: (id) =>
      new RegExp(
        `<!--\\s*BEGIN GENERATED:\\s*${id}\\s*-->[\\s\\S]*?<!--\\s*END GENERATED:\\s*${id}\\s*-->`,
        "g"
      ),
    begin: (id) => `<!-- BEGIN GENERATED: ${id} -->`,
    end: (id) => `<!-- END GENERATED: ${id} -->`
  },
  mdx: {
    header: (id) =>
      `{/* GENERATED BY scripts/generate-docs-metadata.mjs — DO NOT EDIT. Block: ${id}. */}`,
    beginRe: (id) =>
      new RegExp(
        `\\{\\/\\*\\s*BEGIN GENERATED:\\s*${id}\\s*\\*\\/\\}[\\s\\S]*?\\{\\/\\*\\s*END GENERATED:\\s*${id}\\s*\\*\\/\\}`,
        "g"
      ),
    begin: (id) => `{/* BEGIN GENERATED: ${id} */}`,
    end: (id) => `{/* END GENERATED: ${id} */}`
  }
};

// Files under docs/** are MDX-parsed by Docusaurus. Everything else defaults
// to HTML-comment sentinels (GitHub-rendered Markdown).
function dialectFor(relPath) {
  return relPath.startsWith("docs/") ? DIALECTS.mdx : DIALECTS.html;
}

// ---------------------------------------------------------------------------
// Metadata loading
// ---------------------------------------------------------------------------

export function loadMetadata(repoRoot) {
  const pkg = JSON.parse(
    readFileSync(resolve(repoRoot, "package.json"), "utf8")
  );
  const shared = JSON.parse(
    readFileSync(resolve(repoRoot, "metadata/sdk.json"), "utf8")
  );

  if (typeof pkg.name !== "string" || pkg.name.length === 0) {
    throw new Error("package.json is missing a `name` field");
  }
  if (typeof pkg.version !== "string" || pkg.version.length === 0) {
    throw new Error("package.json is missing a `version` field");
  }
  if (typeof shared.docsUrl !== "string" || shared.docsUrl.length === 0) {
    throw new Error("metadata/sdk.json is missing a `docsUrl` field");
  }
  if (typeof shared.distTag !== "string" || shared.distTag.length === 0) {
    throw new Error("metadata/sdk.json is missing a `distTag` field");
  }

  return {
    packageName: pkg.name,
    version: pkg.version,
    homepage: pkg.homepage ?? "",
    repositoryUrl:
      typeof pkg.repository === "object" && pkg.repository?.url
        ? String(pkg.repository.url)
        : "",
    docsUrl: shared.docsUrl,
    distTag: shared.distTag,
    cliPackageName: shared.cliPackageName ?? "",
    installCommands: shared.installCommands ?? {}
  };
}

// ---------------------------------------------------------------------------
// Block renderers — each returns the INNER body of a named generated block
// (excluding the sentinels themselves). Keep each block small and focused so
// docs authors can adopt them independently.
// ---------------------------------------------------------------------------

function renderInstallCommands(meta, dialect) {
  const latest = meta.installCommands.latest ?? {};
  return [
    dialect.header("install-commands"),
    "",
    "```bash",
    latest.pnpm ?? `pnpm add ${meta.packageName}`,
    "# or",
    latest.npm ?? `npm install ${meta.packageName}`,
    "# or",
    latest.yarn ?? `yarn add ${meta.packageName}`,
    "```"
  ].join("\n");
}

function renderInstallDistTag(meta, dialect) {
  const dt = meta.installCommands.distTag ?? {};
  const pinnedTemplate =
    meta.installCommands.pinned?.pnpm ?? `pnpm add ${meta.packageName}@<VERSION>`;
  const pinnedExample = pinnedTemplate.replace("<VERSION>", meta.version);
  return [
    dialect.header("install-dist-tag"),
    "",
    "```bash",
    `${dt.pnpm ?? `pnpm add ${meta.packageName}@${meta.distTag}`}                # latest ${meta.distTag} (tracks @${meta.distTag} dist-tag)`,
    `${pinnedExample}      # pin exact — replace the version with the`,
    `                                               # desired release from npmjs.com/package/${encodeURIComponent(
      meta.packageName
    )}`,
    "```"
  ].join("\n");
}

function renderPackageIdentity(meta, dialect) {
  return [
    dialect.header("package-identity"),
    "",
    `- **Package name:** \`${meta.packageName}\``,
    `- **Current version:** \`${meta.version}\` (npm dist-tag \`${meta.distTag}\`)`,
    `- **Documentation:** ${meta.docsUrl}`,
    ...(meta.cliPackageName
      ? [`- **CLI package:** \`${meta.cliPackageName}\``]
      : [])
  ].join("\n");
}

function renderCurrentVersionPin(meta, dialect) {
  const npmPinned =
    meta.installCommands.pinned?.npm ??
    `npm install ${meta.packageName}@<VERSION>`;
  return [
    dialect.header("current-version-pin"),
    "",
    `\`${npmPinned.replace("<VERSION>", meta.version)}\``
  ].join("\n");
}

// Map of block id -> renderer. Adding a new generated block means adding one
// entry here, wrapping the target snippet with matching sentinels, and re-running
// the generator. No other wiring is required.
const BLOCKS = {
  "install-commands": renderInstallCommands,
  "install-dist-tag": renderInstallDistTag,
  "package-identity": renderPackageIdentity,
  "current-version-pin": renderCurrentVersionPin
};

// ---------------------------------------------------------------------------
// File rewrite
// ---------------------------------------------------------------------------

export function rewriteFile(filePath, meta, relPath) {
  const original = readFileSync(filePath, "utf8");
  const dialect = dialectFor(relPath);
  let updated = original;
  const rewritten = [];

  for (const [id, render] of Object.entries(BLOCKS)) {
    const re = dialect.beginRe(id);
    if (!re.test(updated)) continue;
    // Reset lastIndex — /g regex object was consumed by `.test()`.
    re.lastIndex = 0;
    const body = render(meta, dialect);
    const replacement = `${dialect.begin(id)}\n${body}\n${dialect.end(id)}`;
    updated = updated.replace(re, replacement);
    rewritten.push(id);
  }

  if (updated !== original) {
    writeFileSync(filePath, updated);
  }

  return { changed: updated !== original, rewritten };
}

// ---------------------------------------------------------------------------
// Entrypoint
// ---------------------------------------------------------------------------

// Files the generator considers. A file that has no matching sentinels is a
// no-op — this list is intentionally permissive so new generated blocks can be
// added without touching this script.
const TARGET_FILES = [
  "README.md",
  "docs/02-quick-start/index.md"
];

export function runGenerator({
  repoRoot,
  targets = TARGET_FILES,
  logger = console
} = {}) {
  const meta = loadMetadata(repoRoot);
  const results = [];
  for (const rel of targets) {
    const abs = resolve(repoRoot, rel);
    const result = rewriteFile(abs, meta, rel);
    results.push({ file: rel, ...result });
    if (result.changed) {
      logger.log(
        `[generate-docs-metadata] rewrote ${rel} (blocks: ${result.rewritten.join(", ")})`
      );
    }
  }
  return { meta, results };
}

function main() {
  const scriptDir = dirname(fileURLToPath(import.meta.url));
  const repoRoot = resolve(scriptDir, "..");
  const { results } = runGenerator({ repoRoot });
  const changed = results.filter((r) => r.changed);
  if (changed.length === 0) {
    console.log(
      "[generate-docs-metadata] no generated blocks required rewriting"
    );
  } else {
    console.log(
      `[generate-docs-metadata] rewrote ${changed.length} file(s): ${changed
        .map((c) => relative(repoRoot, resolve(repoRoot, c.file)))
        .join(", ")}`
    );
  }
}

// Only run when executed directly (matches write-cjs-package-json.mjs pattern),
// so unit tests can import the pure functions without side effects.
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  main();
}
